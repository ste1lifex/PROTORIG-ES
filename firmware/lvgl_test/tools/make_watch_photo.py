"""Offline watch image import: Pillow only; no device JPEG decoder or animation.
Run without arguments to rebuild assets/watch_photo/config.json.
--input imports a new image into the project; --position-y 0..1 adjusts its crop.
"""
from pathlib import Path
import argparse
import hashlib
import json
import math
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/watch_photo'
W, H, Y = 480, 232, 248

def smooth(v):
    v = max(0, min(1, v))
    return v*v*(3-2*v)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path)
    parser.add_argument('--position-x', type=float)
    parser.add_argument('--position-y', type=float)
    args = parser.parse_args()
    config_path = ASSETS / 'config.json'
    cfg = json.loads(config_path.read_text(encoding='utf-8'))
    for key, value in [('position_x', args.position_x), ('position_y', args.position_y)]:
        if value is not None:
            cfg[key] = value
        if not 0 <= cfg[key] <= 1:
            parser.error(f'{key} must be in [0, 1]')
    if cfg['top_fade'] <= 0 or cfg['edge_fade'] <= 0 or not 0 <= cfg['bottom_dim'] <= 1:
        parser.error('fade distances must be positive; bottom_dim must be in [0, 1]')
    if args.input:
        # Keep a portable source in the repository, never a developer's absolute path.
        with Image.open(args.input) as source:
            ImageOps.exif_transpose(source).convert('RGB').save(ASSETS / 'source.png')
        cfg['source'] = 'source.png'
    with Image.open(ASSETS / cfg['source']) as source:
        source = ImageOps.exif_transpose(source).convert('RGB')
    w, h = source.size
    scale = max(W/w, H/h)
    cw, ch = W/scale, H/scale
    x0, y0 = (w-cw)*cfg['position_x'], (h-ch)*cfg['position_y']
    image = source.crop((x0, y0, x0+cw, y0+ch)).resize((W,H), Image.Resampling.LANCZOS)
    data = bytearray()
    preview = Image.new('RGB',(W,H))
    for yy in range(H):
        y = yy+Y
        for x in range(W):
            fade = smooth(yy/cfg['top_fade'])*smooth((207-math.hypot(x-240,y-240))/cfg['edge_fade'])
            fade *= 1-cfg['bottom_dim']*smooth((y-350)/73)
            r,g,b = (int(v*fade) for v in image.getpixel((x,yy)))
            value = ((r>>3)<<11)|((g>>2)<<5)|(b>>3)
            data.extend(value.to_bytes(2,'little'))
            preview.putpixel((x,yy),(((value>>11)&31)*255//31,((value>>5)&63)*255//63,(value&31)*255//31))
    lines = [', '.join(f'0x{v:02x}' for v in data[i:i+24])+',' for i in range(0,len(data),24)]
    (ROOT/'watch_photo.c').write_text(
        '/* Generated by tools/make_watch_photo.py; edit the source/config, not this array. */\n'
        '#include "watch_photo.h"\n'
        'const uint8_t watch_photo_pixels[WATCH_PHOTO_BYTES] __attribute__((aligned(64))) = {\n'
        +'\n'.join(lines)+'\n};\n',encoding='utf-8')
    preview.save(ASSETS/'preview.png')
    cfg['pixel_sha256'] = hashlib.sha256(data).hexdigest()
    config_path.write_text(json.dumps(cfg,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(f'Generated {W}x{H} RGB565: {len(data)} bytes; SHA256 {cfg["pixel_sha256"]}')

if __name__ == '__main__':
    main()
